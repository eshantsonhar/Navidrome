"""
M3U playlist writer
Generates recommendation playlists in M3U format
"""

import logging
from pathlib import Path
from typing import List, Dict, Optional
from datetime import datetime
import tempfile
import shutil

import config
from database import Database
from .ranking import CandidateScore

logger = logging.getLogger(__name__)


class PlaylistWriter:
    """Writes M3U playlists"""

    def __init__(self, database: Database):
        self.database = database
        self.config = config.get_config()

    def write_recommendation_playlist(
        self,
        candidates: List[CandidateScore],
        output_path: str = None
    ) -> str:
        """
        Write recommendation playlist to M3U file

        Args:
            candidates: List of scored candidates
            output_path: Path for output file. If None, uses configured path.

        Returns:
            Path to written file
        """
        if output_path is None:
            output_path = self.config.paths.recommendation_playlist

        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)

        # Generate M3U content
        content = self._generate_m3u_content(candidates)

        # Write to temporary file first
        temp_file = output_file.with_suffix('.tmp')
        with open(temp_file, 'w', encoding='utf-8') as f:
            f.write(content)

        # Validate temporary file
        if not self._validate_playlist(temp_file, candidates):
            logger.error("Playlist validation failed, not replacing original")
            if output_file.exists():
                logger.info("Preserving previous valid playlist")
            temp_file.unlink()
            raise ValueError("Playlist validation failed")

        # Atomic replace
        temp_file.replace(output_file)

        logger.info(f"Wrote recommendation playlist to {output_path} with {len(candidates)} tracks")
        return str(output_file)

    def _generate_m3u_content(self, candidates: List[CandidateScore]) -> str:
        """Generate M3U playlist content"""
        lines = ["#EXTM3U"]
        lines.append(f"# Generated by BlackBerry Music Intelligence at {datetime.now().isoformat()}")

        for idx, candidate in enumerate(candidates):
            # Get track info
            track = self._get_track_info(candidate.track_id)
            if not track:
                logger.warning(f"Track {candidate.track_id} not found, skipping")
                continue

            # Verify file exists
            file_path = Path(track['file_path'])
            if not file_path.exists():
                logger.warning(f"File not found: {track['file_path']}, skipping")
                continue

            # Convert to relative path if possible
            relative_path = self._make_relative_path(track['file_path'])

            # Add EXTINF line with metadata
            duration = int(track.get('duration_seconds', 0))
            artist = track.get('artist', 'Unknown')
            title = track.get('title', 'Unknown')
            lines.append(f"#EXTINF:{duration},{artist} - {title}")

            # Add file path
            lines.append(relative_path)

        return "\n".join(lines)

    def _get_track_info(self, track_id: int) -> Optional[Dict]:
        """Get track information from database"""
        with self.database.connect() as conn:
            cursor = conn.execute(
                "SELECT * FROM tracks WHERE id = ?",
                (track_id,)
            )
            row = cursor.fetchone()
            if row:
                return dict(row)
            return None

    def _make_relative_path(self, file_path: str) -> str:
        """
        Convert absolute path to relative path for M3U

        Args:
            file_path: Absolute file path

        Returns:
            Relative path or original path if conversion fails
        """
        try:
            file_obj = Path(file_path).resolve()
            music_base = Path(self.config.paths.music_base).resolve()

            # Try to make relative to music base
            try:
                relative = file_obj.relative_to(music_base)
                return str(relative)
            except ValueError:
                # Not relative to music base, return absolute
                logger.debug(f"Path {file_obj} is not relative to music base {music_base}")
                return file_path
        except Exception as e:
            logger.warning(f"Error making path relative: {e}")
            return file_path

    def _validate_playlist(self, playlist_path: Path, expected_candidates: List[CandidateScore]) -> bool:
        """
        Validate generated playlist

        Args:
            playlist_path: Path to playlist file
            expected_candidates: Expected candidates in playlist

        Returns:
            True if valid, False otherwise
        """
        try:
            # Check file exists and is readable
            if not playlist_path.exists():
                logger.error(f"Playlist file does not exist: {playlist_path}")
                return False

            # Check file is not empty
            if playlist_path.stat().st_size == 0:
                logger.error("Playlist file is empty")
                return False

            # Parse and verify entries
            with open(playlist_path, 'r', encoding='utf-8') as f:
                lines = f.readlines()

            # Check for M3U header
            if not lines or not lines[0].startswith('#EXTM3U'):
                logger.error("Invalid M3U header")
                return False

            # Count non-comment lines (actual track entries)
            track_count = sum(1 for line in lines if line and not line.startswith('#'))

            # Verify track count matches (allowing for skipped files)
            if track_count == 0:
                logger.error("No tracks in playlist")
                return False

            logger.info(f"Playlist validation passed: {track_count} tracks")
            return True

        except Exception as e:
            logger.error(f"Playlist validation error: {e}")
            return False

    def write_chart_playlist(
        self,
        tracks: List[Dict],
        output_path: str = None
    ) -> str:
        """
        Write Top 100 chart playlist

        Args:
            tracks: List of track dictionaries with rank
            output_path: Path for output file

        Returns:
            Path to written file
        """
        if output_path is None:
            output_path = self.config.paths.top_100_playlist

        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)

        # Sort by rank
        sorted_tracks = sorted(tracks, key=lambda x: x.get('rank', 999))

        # Generate M3U content
        lines = ["#EXTM3U"]
        lines.append(f"# YouTube Music Top 100 English - Generated at {datetime.now().isoformat()}")

        for track in sorted_tracks:
            # Get track info
            track_id = track.get('track_id')
            if not track_id:
                continue

            track_info = self._get_track_info(track_id)
            if not track_info:
                continue

            # Verify file exists
            file_path = Path(track_info['file_path'])
            if not file_path.exists():
                continue

            # Convert to relative path
            relative_path = self._make_relative_path(track_info['file_path'])

            # Add EXTINF line with rank
            duration = int(track_info.get('duration_seconds', 0))
            artist = track_info.get('artist', 'Unknown')
            title = track_info.get('title', 'Unknown')
            rank = track.get('rank', 0)

            lines.append(f"#EXTINF:{duration},{rank}. {artist} - {title}")
            lines.append(relative_path)

        # Write to temporary file first
        temp_file = output_file.with_suffix('.tmp')
        with open(temp_file, 'w', encoding='utf-8') as f:
            f.write("\n".join(lines))

        # Atomic replace
        temp_file.replace(output_file)

        logger.info(f"Wrote chart playlist to {output_path} with {len(sorted_tracks)} tracks")
        return str(output_file)

    def copy_tracks_to_recommendation_dir(self, candidates: List[CandidateScore]) -> Dict[str, int]:
        """
        Copy recommended tracks to recommendation directory

        Args:
            candidates: List of scored candidates

        Returns:
            Dictionary with copy statistics
        """
        stats = {
            'copied': 0,
            'skipped': 0,
            'failed': 0
        }

        rec_dir = Path(self.config.paths.recommendation_dir)
        rec_dir.mkdir(parents=True, exist_ok=True)

        for candidate in candidates:
            track = self._get_track_info(candidate.track_id)
            if not track:
                stats['failed'] += 1
                continue

            source_path = Path(track['file_path'])
            if not source_path.exists():
                stats['skipped'] += 1
                continue

            # Check if already in recommendation directory
            try:
                if source_path.parent == rec_dir:
                    stats['skipped'] += 1
                    continue
            except:
                pass

            # Copy file
            try:
                dest_path = rec_dir / source_path.name
                # Handle name conflicts
                if dest_path.exists():
                    base = dest_path.stem
                    ext = dest_path.suffix
                    counter = 1
                    while dest_path.exists():
                        dest_path = rec_dir / f"{base}_{counter}{ext}"
                        counter += 1

                shutil.copy2(source_path, dest_path)
                stats['copied'] += 1
                logger.debug(f"Copied {source_path} to {dest_path}")
            except Exception as e:
                logger.error(f"Failed to copy {source_path}: {e}")
                stats['failed'] += 1

        logger.info(f"Copy statistics: {stats}")
        return stats
