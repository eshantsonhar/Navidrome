def test_atomic_write_preserves_previous_on_failure(temp_db, sample_tracks, temp_music_dir):
    """Test that atomic write preserves previous playlist on validation failure"""
    with tempfile.TemporaryDirectory() as tmpdir:
        from config import Config, PathsConfig
        output_path = os.path.join(tmpdir, "test.m3u")
        test_config = Config(
            paths=PathsConfig(
                music_base=str(temp_music_dir),
                project_dir=tmpdir,
                recommendation_playlist=output_path
            )
        )

        import config
        original_get_config = config.get_config
        config.get_config = lambda: test_config

        try:
            writer = PlaylistWriter(temp_db)

            candidates = [
                CandidateScore(
                    track_id=sample_tracks[0],
                    title="Song 1",
                    artist="Artist 1",
                    score=0.9,
                    reason="Test",
                    details={}
                )
            ]

            initial_output = writer.write_recommendation_playlist(candidates)
            initial_content = Path(initial_output).read_text(encoding='utf-8')

            assert "Song 1" in initial_content
            assert os.path.exists(initial_output)

            writer._validate_playlist = lambda path, candidates: False

            try:
                writer.write_recommendation_playlist(candidates)
                assert False, "Should have raised ValueError"
            except ValueError:
                pass

            assert os.path.exists(initial_output), f"Original playlist at {initial_output} should still exist"
            preserved_content = Path(initial_output).read_text(encoding='utf-8')
            assert preserved_content == initial_content

        finally:
            config.get_config = original_get_config


